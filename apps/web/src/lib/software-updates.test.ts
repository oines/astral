import { afterEach, describe, expect, it, vi } from 'vitest'
import { SoftwareUpdates, UpdateRequestError, updateResponse, type SoftwareUpdateState } from './software-updates'
const available: SoftwareUpdateState = { phase: 'available', currentVersion: '0.1.2', version: '0.1.3', manager: 'desktop' }
const running: SoftwareUpdateState = { ...available, phase: 'installing', operationId: 'operation-a', operationVersion: '0.1.3', operationState: 'running' }
const complete: SoftwareUpdateState = { ...running, phase: 'current', currentVersion: '0.1.3', operationState: 'complete' }
function fixture() {
  const transport = { state: vi.fn(async () => available), check: vi.fn(async () => available), apply: vi.fn(async () => running) }
  const data = new Map<string, string>()
  const storage = { getItem: (key: string) => data.get(key) || null, setItem: (key: string, value: string) => { data.set(key, value) }, removeItem: (key: string) => { data.delete(key) } }
  const monitor = new SoftwareUpdates(transport, storage)
  monitor.onUpdated = vi.fn()
  return { transport, monitor, storage, data }
}
afterEach(() => { vi.clearAllTimers(); vi.useRealTimers() })
describe('browser Server update tracking', () => {
  it('checks metadata without calling apply and retains an explicit check failure', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    f.transport.check.mockRejectedValueOnce(new Error('Metadata unavailable'))
    await f.monitor.act('check')
    expect(f.monitor.state).toMatchObject({ phase: 'error', retry: 'check', error: 'Metadata unavailable' })
    expect(f.transport.apply).not.toHaveBeenCalled()
    f.monitor.stop()
  })
  it('waits across installation disconnect and confirms only the same operation and exact target', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    await f.monitor.act('update')
    f.transport.state.mockRejectedValueOnce(new Error('Disconnected'))
    await f.monitor.refresh()
    expect(f.monitor.waiting).toBe(true)
    expect(f.monitor.error).toBe('')
    expect(f.monitor.busy).toBe(true)
    f.transport.state.mockResolvedValueOnce(complete)
    await f.monitor.refresh()
    expect(f.monitor.waiting).toBe(false)
    expect(f.monitor.busy).toBe(false)
    expect(f.monitor.state?.currentVersion).toBe('0.1.3')
    expect(f.data.size).toBe(0)
    expect(f.monitor.onUpdated).toHaveBeenCalledOnce()
    f.monitor.stop()
  })
  it('never claims success from a different running version or a different operation', async () => {
    vi.useFakeTimers()
    for (const state of [{ ...complete, currentVersion: '0.1.4' }, { ...complete, operationId: 'operation-b' }]) {
      const f = fixture()
      await f.monitor.start()
      await f.monitor.act('update')
      f.transport.state.mockResolvedValueOnce(state)
      await f.monitor.refresh()
      expect(f.monitor.error).toMatch(/does not match|could not be confirmed/)
      f.monitor.stop()
    }
  })
  it('reconciles a lost apply acknowledgement by observing the newly queued operation instead of reposting', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    f.transport.apply.mockRejectedValueOnce(new Error('HTTP connection closed'))
    await f.monitor.act('update')
    expect(f.monitor.waiting).toBe(true)
    f.transport.state.mockResolvedValueOnce(complete)
    await f.monitor.refresh()
    expect(f.monitor.busy).toBe(false)
    expect(f.monitor.error).toBe('')
    expect(f.transport.apply).toHaveBeenCalledOnce()
    f.monitor.stop()
  })
  it('recovers a pending operation after page reload and preserves its reported failure', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    await f.monitor.act('update')
    f.monitor.stop()
    f.transport.state.mockResolvedValueOnce({ ...running, phase: 'error', operationState: 'failed', error: 'Signature mismatch', retry: 'update' })
    const reopened = new SoftwareUpdates(f.transport, f.storage)
    await reopened.start()
    expect(reopened.state).toMatchObject({ phase: 'error', retry: 'update', error: 'Signature mismatch' })
    expect(reopened.busy).toBe(false)
    reopened.stop()
  })
  it('polls metadata state during another browser update and prevents duplicate apply', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.transport.state.mockResolvedValueOnce(running).mockResolvedValueOnce(complete)
    await f.monitor.start()
    await f.monitor.act('update')
    expect(f.transport.apply).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1000)
    expect(f.monitor.busy).toBe(false)
    f.monitor.stop()
  })
  for (const [status, message] of [[409, 'An update check is already running; try again.'], [401, 'The login session has expired.']] as const) {
    it(`reports an explicit HTTP ${status} rejection immediately instead of waiting for a restart`, async () => {
      vi.useFakeTimers()
      const f = fixture()
      await f.monitor.start()
      f.transport.apply.mockRejectedValueOnce(new UpdateRequestError(message, status))
      await f.monitor.act('update')
      expect(f.monitor.state).toMatchObject({ phase: 'error', retry: 'update', error: message })
      expect(f.monitor.waiting).toBe(false)
      expect(f.monitor.busy).toBe(false)
      expect(f.data.size).toBe(0)
      await f.monitor.refresh()
      expect(f.monitor.error).toBe(message)
      expect(f.monitor.state?.retry).toBe('update')
      f.monitor.stop()
    })
  }
  it('retains HTTP status and the actual Owner API error message', async () => {
    await expect(updateResponse(Promise.resolve({ error: { message: 'Metadata check busy' }, response: new Response('{}', { status: 409 }) }))).rejects.toMatchObject({ status: 409, message: 'Metadata check busy' })
  })
  it('restores a pending update after sixty minutes and only gives up after the confirmation budget', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    await f.monitor.act('update')
    f.monitor.stop()
    vi.setSystemTime(Date.now() + 65 * 60_000)
    f.transport.state.mockRejectedValueOnce(new Error('Still restarting'))
    const reopened = new SoftwareUpdates(f.transport, f.storage)
    await reopened.start()
    expect(reopened.waiting).toBe(true)
    vi.setSystemTime(Date.now() + 16 * 60_000)
    f.transport.state.mockRejectedValueOnce(new Error('Still offline'))
    await reopened.refresh()
    expect(reopened.waiting).toBe(false)
    expect(reopened.error).toContain('could not be confirmed')
    expect(f.data.size).toBe(0)
    reopened.stop()
  })
  it('treats a server-side 503 as an uncertain apply acknowledgement', async () => {
    vi.useFakeTimers()
    const f = fixture()
    await f.monitor.start()
    f.transport.apply.mockRejectedValueOnce(new UpdateRequestError('Service stopping', 503))
    await f.monitor.act('update')
    expect(f.monitor.waiting).toBe(true)
    expect(f.monitor.error).toBe('')
    expect(f.data.size).toBe(1)
    expect(f.transport.apply).toHaveBeenCalledOnce()
    f.monitor.stop()
  })
})
